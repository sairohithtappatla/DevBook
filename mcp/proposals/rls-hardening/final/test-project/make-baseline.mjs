// Derives 00_baseline_schema.sql (the application schema as it is in production TODAY, before any hardening) from sandbox/schema.sql
// by removing the sandbox-only stand-ins (roles, auth schema/users/uid, blanket GRANTs). Deterministic: re-run after editing schema.sql.
//   node make-baseline.mjs            writes 00_baseline_schema.sql
//   node make-baseline.mjs --check    exits 1 if the committed file is stale
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const here = path.dirname(fileURLToPath(import.meta.url));
const src = fs.readFileSync(path.join(here, "../sandbox/schema.sql"), "utf8").replace(/\r\n/g, "\n");
const a = src.indexOf("DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon')");
const b = src.indexOf("CREATE TYPE access_level");
const c = src.indexOf("-- ASSUMPTION (grants)");
if (a < 0 || b < 0 || c < 0 || !(a < b && b < c)) throw new Error("schema.sql no longer has the expected markers");
const header = `-- BASELINE for a FRESH InsForge TEST project: the DevBook application schema as it is in production today (before 01-04).
-- Generated by make-baseline.mjs from sandbox/schema.sql. NOT applied anywhere. Load into the TEST project only.
-- Exact in production export: users, books, phases, steps, book_members, attachments (columns), all functions, triggers, indexes, policies.
-- RECONSTRUCTED (parity gap, see README): book_access, user_followers, step_progress, book_progress, book_revisions columns;
-- enum values of book_difficulty and step_type are assumed. book_invitations is not reproduced. Roles, auth.users, auth.uid() and
-- default privileges come from the platform; nothing here creates them.
`;
const out = header + "BEGIN;\n\n" + src.slice(b, c).trimEnd() + "\n\nCOMMIT;\n";
const file = path.join(here, "00_baseline_schema.sql");
if (process.argv.includes("--check")) {
  const cur = fs.existsSync(file) ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") : "";
  if (cur !== out) { console.error("00_baseline_schema.sql is stale: run node make-baseline.mjs"); process.exit(1); }
  console.log("00_baseline_schema.sql is up to date"); process.exit(0);
}
fs.writeFileSync(file, out);
console.log(`wrote 00_baseline_schema.sql (${out.split("\n").length} lines)`);
